#!/usr/bin/env node
// Writes the GPUI app's syntax highlighting: every grammar the app has, from the
// same @shikijs/langs as the TS app, each compressed on its own so a language loads
// only what it needs, and the scope-to-colour table of createCodeTheme. `--check`
// fails when either is out of date instead of writing.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { gunzipSync, gzipSync } from "node:zlib";
import {
  localLanguages,
  shikiGrammars,
  typescriptLoader,
} from "./lib/generated.mjs";

const root = resolve(import.meta.dirname, "..");
const langsDir = resolve(root, "node_modules/@shikijs/langs");
const assetsDir = resolve(root, "app/assets");
const indexPath = resolve(assetsDir, "syntax.json");
const grammarsPath = resolve(assetsDir, "grammars.bin");
const check = process.argv.includes("--check");

const { version } = JSON.parse(
  await readFile(resolve(langsDir, "package.json"), "utf8"),
);

const { sources, embeds, aliases } = await shikiGrammars(langsDir);

// Languages Shiki has no grammar for, kept beside the app's other shared source.
for (const [id, { grammar }] of Object.entries(await localLanguages())) {
  if (sources[id] || aliases[id])
    throw new Error(`${id} is already a Shiki grammar`);
  sources[id] = JSON.stringify(JSON.parse(grammar));
  embeds[id] = [];
}

const grammars = Object.fromEntries(
  Object.entries(sources).map(([id, text]) => [id, JSON.parse(text)]),
);
const idOfScope = new Map(
  Object.entries(grammars).map(([id, grammar]) => [grammar.scopeName, id]),
);
for (const [id, grammar] of Object.entries(grammars)) {
  for (const alias of grammar.aliases ?? []) aliases[alias] ??= id;
}

/** The grammars a language names: its embedded languages and every grammar it includes by scope. */
function named(grammar) {
  const found = new Set();
  const visit = (node) => {
    if (Array.isArray(node)) return node.forEach(visit);
    if (!node || typeof node !== "object") return;
    for (const [key, value] of Object.entries(node)) {
      if (key === "include" && typeof value === "string") {
        const id = idOfScope.get(value.split("#")[0]);
        if (id) found.add(id);
      } else visit(value);
    }
  };
  visit(grammar);
  return found;
}

const direct = Object.fromEntries(
  Object.keys(grammars).map((id) => [
    id,
    new Set([...embeds[id], ...named(grammars[id])]),
  ]),
);

/** Every grammar a language can reach, so opening it loads all of them at once. */
function requires(id) {
  const seen = new Set([id]);
  const queue = [id];
  while (queue.length) {
    for (const next of direct[queue.pop()]) {
      if (!seen.has(next)) {
        seen.add(next);
        queue.push(next);
      }
    }
  }
  seen.delete(id);
  return [...seen].sort();
}

const server = await typescriptLoader();
let roles;
try {
  const { createCodeTheme, HIGHLIGHT_KEYS } = await server.ssrLoadModule(
    "/shared/chat/codeTheme.ts",
  );
  const keyed = Object.fromEntries(HIGHLIGHT_KEYS.map((key) => [key, key]));
  const theme = createCodeTheme(
    {
      dark: true,
      editor: { bg: "transparent", fg: "" },
      chrome: { bg: "" },
      highlight: keyed,
    },
    "roles",
  );
  roles = theme.tokenColors.flatMap(({ scope, settings }) =>
    scope.map((selector) => [
      selector,
      settings.foreground,
      settings.fontStyle ?? null,
    ]),
  );
} finally {
  await server.close();
}

const ids = Object.keys(grammars).sort();
const packed = ids.map((id) => gzipSync(sources[id], { level: 9 }));
let at = 0;
const index = {
  notice: "Generated by scripts/generate-syntax.mjs. Do not edit by hand.",
  version,
  grammars: Object.fromEntries(
    ids.map((id, i) => {
      const entry = {
        scope: grammars[id].scopeName,
        requires: requires(id),
        at,
        size: packed[i].length,
      };
      at += packed[i].length;
      return [id, entry];
    }),
  ),
  aliases: Object.fromEntries(Object.entries(aliases).sort()),
  roles,
};

/** Compressed grammars are compared by what they hold, since zlib versions differ in the bytes they write. */
async function current() {
  try {
    const kept = JSON.parse(await readFile(indexPath, "utf8"));
    const bytes = await readFile(grammarsPath);
    const unpacked = Object.fromEntries(
      Object.entries(kept.grammars).map(([id, { at, size }]) => [
        id,
        gunzipSync(bytes.subarray(at, at + size)).toString("utf8"),
      ]),
    );
    return { kept, unpacked };
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
}

const strip = ({ grammars, ...rest }) => ({
  ...rest,
  grammars: Object.fromEntries(
    Object.entries(grammars).map(([id, { scope, requires }]) => [
      id,
      { scope, requires },
    ]),
  ),
});

const existing = await current();
const fresh =
  existing &&
  JSON.stringify(strip(existing.kept)) === JSON.stringify(strip(index)) &&
  ids.every((id) => existing.unpacked[id] === sources[id]);
if (!fresh) {
  if (check)
    throw new Error(
      `Generated syntax highlighting is stale: run pnpm syntax:generate`,
    );
  await writeFile(grammarsPath, Buffer.concat(packed));
  await writeFile(indexPath, `${JSON.stringify(index, null, 1)}\n`);
}
