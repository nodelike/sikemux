import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import prettier from "prettier";

const root = resolve(import.meta.dirname, "..");
const langsDir = resolve(root, "node_modules/@shikijs/langs");
const rustOutputPath = resolve(root, "src-tauri/grammars.json");
const tsOutputPath = resolve(root, "src/languages/generated/grammars.ts");
const check = process.argv.includes("--check");

const { version } = JSON.parse(
  await readFile(resolve(langsDir, "package.json"), "utf8"),
);
const shikiVersion = JSON.parse(
  await readFile(resolve(root, "node_modules/shiki/package.json"), "utf8"),
).version;
if (version !== shikiVersion) {
  throw new Error(
    `@shikijs/langs ${version} and shiki ${shikiVersion} must be the same version`,
  );
}

const GRAMMAR =
  /^const lang = Object\.freeze\(JSON\.parse\(("(?:[^"\\]|\\.)*")\)\)$/m;
const IMPORT = /^import \w+ from '\.\/([\w.+-]+)\.mjs'$/gm;
const ALIAS = /^export \{ default \} from '\.\/([\w.+-]+)\.mjs'$/m;

const files = (await readdir(resolve(langsDir, "dist")))
  .filter((name) => name.endsWith(".mjs") && name !== "index.mjs")
  .sort();

const hashes = {};
const embeds = {};
const aliases = {};
for (const file of files) {
  const id = file.slice(0, -".mjs".length);
  const source = await readFile(resolve(langsDir, "dist", file), "utf8");
  const alias = ALIAS.exec(source);
  if (alias) {
    aliases[id] = alias[1];
    continue;
  }
  const literal = GRAMMAR.exec(source);
  if (!literal) throw new Error(`Unrecognised grammar module: ${file}`);
  const grammar = JSON.parse(JSON.parse(literal[1]));
  if (grammar.name !== id)
    throw new Error(`${file} declares the grammar ${grammar.name}`);
  hashes[id] = createHash("sha256").update(source).digest("hex");
  embeds[id] = [...source.matchAll(IMPORT)].map((match) => match[1]);
}

for (const [alias, target] of Object.entries(aliases)) {
  if (!hashes[target])
    throw new Error(`${alias} points at a missing grammar: ${target}`);
}
for (const [id, needs] of Object.entries(embeds)) {
  for (const embed of needs) {
    if (!hashes[embed])
      throw new Error(`${id} embeds a missing grammar: ${embed}`);
  }
}

const notice =
  "Generated by scripts/generate-grammars.mjs. Do not edit by hand.";
const rustOutput = `${JSON.stringify({ notice, version, sha256: hashes }, null, 2)}\n`;
const tsSource = `// ${notice}
/** Every grammar there is, each with the grammars it embeds. */
export const GRAMMARS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(embeds)};

/** Other names the same grammars answer to. */
export const GRAMMAR_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliases)};
`;
const tsOutput = await prettier.format(tsSource, {
  ...(await prettier.resolveConfig(tsOutputPath)),
  filepath: tsOutputPath,
});

async function emit(path, expected) {
  let actual = null;
  try {
    actual = await readFile(path, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (actual === expected) return;
  if (check) throw new Error(`Generated grammar manifest is stale: ${path}`);
  await writeFile(path, expected);
}

await emit(rustOutputPath, rustOutput);
await emit(tsOutputPath, tsOutput);
