#!/usr/bin/env node
// Writes the app's copy of the default shortcuts from the table the GPUI app also reads,
// src-tauri/crates/sikemux-core/src/assets/keybindings.json, so both apps start from one
// list. `--check` fails when the copy is out of date instead of writing it.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { format, resolveConfig } from "prettier";

const root = resolve(import.meta.dirname, "..");
const table = resolve(
  root,
  "src-tauri/crates/sikemux-core/src/assets/keybindings.json",
);
const output = resolve(root, "src/commands/generated/keybindings.ts");
const check = process.argv.includes("--check");

const rows = JSON.parse(await readFile(table, "utf8"));
const contents = await format(
  `// Generated by scripts/generate-keybindings.mjs from src-tauri/crates/sikemux-core/src/assets/keybindings.json; do not edit.\n` +
    `export const CORE_KEYBINDINGS = ${JSON.stringify(rows)} as const;\n`,
  { ...(await resolveConfig(output)), filepath: output },
);
const current = await readFile(output, "utf8").catch(() => null);
if (check) {
  if (current !== contents) {
    console.error(
      "src/commands/generated/keybindings.ts is out of date: run pnpm keybindings:generate",
    );
    process.exit(1);
  }
} else if (current !== contents) {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, contents);
}
