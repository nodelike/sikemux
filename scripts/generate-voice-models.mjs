import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outputPath = resolve(root, "src-tauri/voice-models.json");
const check = process.argv.includes("--check");

const MODELS = [
  {
    repo: "FluidInference/parakeet-tdt-0.6b-v3-coreml",
    revision: "7dd20fe6b1797d35f5e3307e8b1732d9a178edfe",
    folder: "parakeet-tdt-0.6b-v3",
    include: [
      "Preprocessor.mlmodelc/",
      "Encoder.mlmodelc/",
      "Decoder.mlmodelc/",
      "JointDecisionv3.mlmodelc/",
      "parakeet_vocab.json",
    ],
  },
];

async function fetchOk(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response;
}

/** Small files are kept in Git rather than LFS, so only their Git object id is listed. */
async function hashSmallFile(model, entry) {
  const url = `https://huggingface.co/${model.repo}/resolve/${model.revision}/${entry.path}`;
  const body = Buffer.from(await (await fetchOk(url)).arrayBuffer());
  const gitId = createHash("sha1")
    .update(`blob ${body.length}\0`)
    .update(body)
    .digest("hex");
  if (gitId !== entry.oid)
    throw new Error(
      `${model.repo}/${entry.path} does not match its Git object id`,
    );
  return createHash("sha256").update(body).digest("hex");
}

const models = [];
for (const model of MODELS) {
  const tree = await (
    await fetchOk(
      `https://huggingface.co/api/models/${model.repo}/tree/${model.revision}?recursive=1`,
    )
  ).json();
  const entries = tree
    .filter((entry) => entry.type === "file")
    .filter((entry) =>
      model.include.some((prefix) =>
        prefix.endsWith("/")
          ? entry.path.startsWith(prefix)
          : entry.path === prefix,
      ),
    )
    .sort((a, b) => a.path.localeCompare(b.path));
  for (const prefix of model.include) {
    if (!entries.some((entry) => entry.path.startsWith(prefix)))
      throw new Error(`${model.repo}@${model.revision} has no ${prefix}`);
  }
  const files = [];
  for (const entry of entries) {
    const sha256 = entry.lfs?.oid ?? (await hashSmallFile(model, entry));
    files.push({ path: entry.path, size: entry.size, sha256 });
  }
  models.push({
    repo: model.repo,
    revision: model.revision,
    folder: model.folder,
    files,
  });
}

const notice =
  "Generated by scripts/generate-voice-models.mjs. Do not edit by hand.";
const output = `${JSON.stringify({ notice, models }, null, 2)}\n`;

let actual = null;
try {
  actual = await readFile(outputPath, "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}
if (actual !== output) {
  if (check) throw new Error(`Voice model manifest is stale: ${outputPath}`);
  await writeFile(outputPath, output);
}
