import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const libPath = resolve(root, "src-tauri/src/lib.rs");
const rustOutputPath = resolve(
  root,
  "src-tauri/src/generated_command_names.rs",
);
const tsOutputPath = resolve(root, "src/api/generated/ipcCommands.ts");
const capabilityPath = resolve(root, "src-tauri/capabilities/default.json");
const check = process.argv.includes("--check");

const lib = await readFile(libPath, "utf8");
const marker = ".invoke_handler(tauri::generate_handler![";
const start = lib.indexOf(marker);
if (start < 0) throw new Error(`Unable to find ${marker} in ${libPath}`);
const bodyStart = start + marker.length;
const end = lib.indexOf("\n        ])", bodyStart);
if (end < 0)
  throw new Error(`Unable to find the end of the invoke handler in ${libPath}`);

const commands = lib
  .slice(bodyStart, end)
  .split(",")
  .map((entry) => entry.trim())
  .filter(Boolean)
  .map((entry) => entry.split("::").at(-1))
  .filter((entry) => /^[a-z][a-z0-9_]*$/u.test(entry));

if (commands.length === 0 || new Set(commands).size !== commands.length) {
  throw new Error(
    "The native command list is empty or contains duplicate command names",
  );
}

const generatedNotice =
  "// Generated by scripts/generate-ipc-contracts.mjs. Do not edit by hand.\n";
const rustOutput = `${generatedNotice}pub const IPC_COMMANDS: &[&str] = &[\n${commands.map((command) => `    ${JSON.stringify(command)},`).join("\n")}\n];\n`;
const tsOutput = `${generatedNotice}export const IPC_COMMANDS = [\n${commands.map((command) => `    ${JSON.stringify(command)},`).join("\n")}\n] as const;\n\nexport type IpcCommand = (typeof IPC_COMMANDS)[number];\n`;
const capability = {
  $schema: "../gen/schemas/desktop-schema.json",
  identifier: "default",
  description: "Generated explicit capability for the main application window",
  webviews: ["main"],
  permissions: [
    "core:default",
    "core:window:allow-start-dragging",
    "dialog:default",
    "notification:default",
    "process:allow-restart",
    "core:window:allow-show",
    "core:window:allow-unminimize",
    "core:window:allow-set-focus",
    "core:webview:allow-set-webview-focus",
    "core:window:allow-set-badge-count",
    "core:window:allow-request-user-attention",
    ...commands.map((command) => `allow-${command.replaceAll("_", "-")}`),
  ],
};
const capabilityOutput = `${JSON.stringify(capability, null, 2)}\n`;

await mkdir(resolve(root, "src/api/generated"), { recursive: true });

async function emit(path, expected) {
  let actual = null;
  try {
    actual = await readFile(path, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (actual === expected) return;
  if (check) throw new Error(`Generated IPC contract is stale: ${path}`);
  await writeFile(path, expected);
}

await emit(rustOutputPath, rustOutput);
await emit(tsOutputPath, tsOutput);
await emit(capabilityPath, capabilityOutput);
