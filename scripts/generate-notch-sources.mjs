#!/usr/bin/env node
// Writes what the notch helper shares with the app: its settings from
// src/notch/settings.json, for the app's TypeScript and the helper's Swift,
// its colours from src/styles/base.css, and the app's buddies from
// src/buddies, which the helper runs to draw them. `--check` fails when one is
// out of date instead of writing it.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { format, resolveConfig } from "prettier";
import { build } from "vite";

const root = resolve(import.meta.dirname, "..");
const settingsSource = resolve(root, "src/notch/settings.json");
const cssSource = resolve(root, "src/styles/base.css");
const tsPath = resolve(root, "src/notch/generated/settings.ts");
const settingsSwiftPath = resolve(
  root,
  "src-tauri/notch/Sources/NotchKit/Settings.generated.swift",
);
const themeSwiftPath = resolve(
  root,
  "src-tauri/notch/Sources/NotchKit/Theme.generated.swift",
);
const buddiesSource = resolve(root, "src/buddies/notch.ts");
const buddiesSwiftPath = resolve(
  root,
  "src-tauri/notch/Sources/NotchKit/Buddies.generated.swift",
);
const check = process.argv.includes("--check");

/** The helper's colour names and the base.css variable each one is. */
const COLOURS = {
  ink: "--ink",
  inkDim: "--ink-dim",
  inkFaint: "--ink-faint",
  accent: "--acc",
  accentSoft: "--acc-soft",
  accentLine: "--acc-line",
  onAccent: "--void",
  live: "--live",
  warn: "--warn",
  command: "--cmd",
  danger: "--danger",
};

async function emit(path, contents) {
  let actual = null;
  try {
    actual = await readFile(path, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (actual === contents) return;
  if (check) throw new Error(`Generated notch source is stale: ${path}`);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
}

async function pretty(path, source) {
  return format(source, { ...(await resolveConfig(path)), filepath: path });
}

const { settings } = JSON.parse(await readFile(settingsSource, "utf8"));
const entries = Object.entries(settings);
for (const [key, setting] of entries) {
  if (!/^[a-z][A-Za-z]*$/.test(key))
    throw new Error(`notch setting ${JSON.stringify(key)} is not camelCase`);
  if (setting.choices) {
    if (!setting.choices.includes(setting.default))
      throw new Error(
        `notch setting ${key} defaults to a value it does not offer`,
      );
  } else if (typeof setting.default !== "boolean") {
    throw new Error(`notch setting ${key} is neither a choice nor a flag`);
  }
}
const helperReads = entries.filter(([, setting]) => !setting.appOnly);
const banner = (source) =>
  `Generated by scripts/generate-notch-sources.mjs from ${source}. Do not edit by hand.`;

await emit(
  tsPath,
  await pretty(
    tsPath,
    `// ${banner("src/notch/settings.json")}
export const NOTCH_SETTING_CHOICES = ${JSON.stringify(
      Object.fromEntries(
        entries
          .filter(([, setting]) => setting.choices)
          .map(([key, setting]) => [key, setting.choices]),
      ),
    )} as const;

export const NOTCH_SETTING_DEFAULTS = ${JSON.stringify(
      Object.fromEntries(
        entries.map(([key, setting]) => [key, setting.default]),
      ),
    )} as const;
`,
  ),
);

const pascal = (key) => key[0].toUpperCase() + key.slice(1);
const swiftType = ([key, setting]) => (setting.choices ? pascal(key) : "Bool");
const swiftValue = ([, setting]) =>
  setting.choices ? `.${setting.default}` : String(setting.default);

await emit(
  settingsSwiftPath,
  `// ${banner("src/notch/settings.json")}

import Foundation

/// The Notch section of Sikemux's settings, which the app writes to a file
/// beside its core and the helper rereads whenever it changes.
struct NotchSettings: Decodable, Equatable {
${helperReads
  .filter(([, setting]) => setting.choices)
  .map(
    ([key, setting]) =>
      `    enum ${pascal(key)}: String, Decodable { case ${setting.choices.join(", ")} }`,
  )
  .join("\n")}

${helperReads
  .map(
    (entry) =>
      `${entry[1].doc ? `    /// ${entry[1].doc}\n` : ""}    var ${entry[0]}: ${swiftType(entry)} = ${swiftValue(entry)}`,
  )
  .join("\n")}

    init() {}

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        let defaults = NotchSettings()
${helperReads
  .map(
    (entry) =>
      `        ${entry[0]} = (try? container.decode(${swiftType(entry)}.self, forKey: .${entry[0]})) ?? defaults.${entry[0]}`,
  )
  .join("\n")}
    }

    private enum CodingKeys: String, CodingKey {
        case ${helperReads.map(([key]) => key).join(", ")}
    }
}
`,
);

const css = await readFile(cssSource, "utf8");
const rootBlock = css.match(/^:root\s*\{([^}]*)\}/m)?.[1];
if (!rootBlock) throw new Error("src/styles/base.css has no :root block");
const variables = Object.fromEntries(
  [...rootBlock.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)].map(
    ([, name, value]) => [name, value.trim()],
  ),
);

const hex = (channel) => Number(channel).toString(16).padStart(2, "0");
function swiftColour(variable) {
  const value = variables[variable];
  if (!value)
    throw new Error(`src/styles/base.css does not define ${variable}`);
  if (/^#[0-9a-f]{6}$/i.test(value))
    return `Color(hex: "${value.toLowerCase()}")`;
  const rgba = value.match(
    /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/,
  );
  if (!rgba)
    throw new Error(`${variable} is ${value}, neither #rrggbb nor rgba()`);
  const [, red, green, blue, alpha] = rgba;
  return `Color(hex: "#${hex(red)}${hex(green)}${hex(blue)}").opacity(${Number(alpha)})`;
}

await emit(
  themeSwiftPath,
  `// ${banner("src/styles/base.css")}

import SwiftUI

extension Theme {
${Object.entries(COLOURS)
  .map(
    ([name, variable]) => `    static let ${name} = ${swiftColour(variable)}`,
  )
  .join("\n")}
}
`,
);

const [bundle] = await build({
  root,
  configFile: false,
  logLevel: "silent",
  build: {
    write: false,
    minify: true,
    lib: { entry: buddiesSource, formats: ["iife"], name: "SikemuxBuddies" },
  },
});
const buddiesScript = bundle.output[0].code.trim();
if (buddiesScript.includes('"""#'))
  throw new Error("the buddies script ends the Swift string it is kept in");

await emit(
  buddiesSwiftPath,
  `// ${banner("src/buddies")}

/// Defines \`SikemuxBuddies.notchBuddy(buddies, agentId, named, state)\`, which returns an agent's buddy as an SVG document, or null when it shows its agent's mark.
let buddiesScript = #"""
${buddiesScript}
"""#
`,
);

console.log(
  `✓ ${entries.length} notch settings, ${Object.keys(COLOURS).length} colours and ${Math.round(buddiesScript.length / 1024)} KB of buddies`,
);
