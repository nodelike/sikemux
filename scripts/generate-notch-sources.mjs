#!/usr/bin/env node
// Writes what the notch helper shares with the app: its settings from
// helpers/notch/settings.json, for the core's Rust and the helper's Swift,
// its colours from shared/ui/palette.css, and the app's buddies from
// shared/buddies as compressed SVG markup. The Swift is build output;
// `--check` fails when the committed Rust is out of date instead of writing it.

import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { deflateRawSync } from "node:zlib";
import { emit, typescriptLoader, write } from "./lib/generated.mjs";

const root = resolve(import.meta.dirname, "..");
const settingsSource = resolve(root, "helpers/notch/settings.json");
const cssSource = resolve(root, "shared/ui/palette.css");
const settingsRustPath = resolve(root, "crates/sikemux-view/src/notch.rs");
const settingsSwiftPath = resolve(
  root,
  "helpers/notch/Sources/NotchKit/Settings.generated.swift",
);
const themeSwiftPath = resolve(
  root,
  "helpers/notch/Sources/NotchKit/Theme.generated.swift",
);
const buddiesSwiftPath = resolve(
  root,
  "helpers/notch/Sources/NotchKit/Buddies.generated.swift",
);
const BUDDY_STATES = ["idle", "working", "waiting", "done", "error"];

/** The helper's colour names and the palette variable each one is. */
const COLOURS = {
  ink: "--ink",
  inkDim: "--ink-dim",
  inkFaint: "--ink-faint",
  accent: "--acc",
  onAccent: "--void",
  live: "--live",
  warn: "--warn",
  command: "--cmd",
  danger: "--danger",
};

const { settings } = JSON.parse(await readFile(settingsSource, "utf8"));
const entries = Object.entries(settings);
for (const [key, setting] of entries) {
  if (!/^[a-z][A-Za-z]*$/.test(key))
    throw new Error(`notch setting ${JSON.stringify(key)} is not camelCase`);
  if (setting.choices) {
    if (!setting.choices.includes(setting.default))
      throw new Error(
        `notch setting ${key} defaults to a value it does not offer`,
      );
  } else if (typeof setting.default !== "boolean") {
    throw new Error(`notch setting ${key} is neither a choice nor a flag`);
  }
}
const helperReads = entries.filter(([, setting]) => !setting.appOnly);
const banner = (source) =>
  `Generated by scripts/generate-notch-sources.mjs from ${source}. Do not edit by hand.`;

const pascal = (key) => key[0].toUpperCase() + key.slice(1);
const snake = (key) =>
  key.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
const rustType = ([key, setting]) =>
  setting.choices ? `Notch${pascal(key)}` : "bool";

await emit(
  settingsRustPath,
  `// ${banner("helpers/notch/settings.json")}

use serde::{Deserialize, Serialize};

/// The Notch section of the person's preferences, which the island reads.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct NotchSettings {
${entries
  .map(
    (entry) =>
      `${entry[1].doc ? `    /// ${entry[1].doc}\n` : ""}    pub ${snake(entry[0])}: ${rustType(entry)},`,
  )
  .join("\n")}
}

impl Default for NotchSettings {
    fn default() -> Self {
        Self {
${entries
  .map(
    ([key, setting]) =>
      `            ${snake(key)}: ${setting.choices ? `Notch${pascal(key)}::${pascal(setting.default)}` : setting.default},`,
  )
  .join("\n")}
        }
    }
}
${entries
  .filter(([, setting]) => setting.choices)
  .map(
    ([key, setting]) => `
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Notch${pascal(key)} {
${setting.choices.map((choice) => `    ${pascal(choice)},`).join("\n")}
}`,
  )
  .join("\n")}
`,
);
const swiftType = ([key, setting]) => (setting.choices ? pascal(key) : "Bool");
const swiftValue = ([, setting]) =>
  setting.choices ? `.${setting.default}` : String(setting.default);

await write(
  settingsSwiftPath,
  `// ${banner("helpers/notch/settings.json")}

import Foundation

/// The Notch section of the person's preferences, which the helper reads from
/// the core and again whenever they change.
struct NotchSettings: Codable, Hashable {
${helperReads
  .filter(([, setting]) => setting.choices)
  .map(
    ([key, setting]) =>
      `    enum ${pascal(key)}: String, Codable, Hashable { case ${setting.choices.join(", ")} }`,
  )
  .join("\n")}

${helperReads
  .map(
    (entry) =>
      `${entry[1].doc ? `    /// ${entry[1].doc}\n` : ""}    var ${entry[0]}: ${swiftType(entry)} = ${swiftValue(entry)}`,
  )
  .join("\n")}

    init() {}

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        let defaults = NotchSettings()
${helperReads
  .map(
    (entry) =>
      `        ${entry[0]} = (try? container.decode(${swiftType(entry)}.self, forKey: .${entry[0]})) ?? defaults.${entry[0]}`,
  )
  .join("\n")}
    }

    private enum CodingKeys: String, CodingKey {
        case ${helperReads.map(([key]) => key).join(", ")}
    }
}
`,
);

const css = await readFile(cssSource, "utf8");
const rootBlock = css.match(/^:root\s*\{([^}]*)\}/m)?.[1];
if (!rootBlock) throw new Error("shared/ui/palette.css has no :root block");
const variables = Object.fromEntries(
  [...rootBlock.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)].map(
    ([, name, value]) => [name, value.trim()],
  ),
);

const hex = (channel) => Number(channel).toString(16).padStart(2, "0");
function swiftColour(variable) {
  const value = variables[variable];
  if (!value)
    throw new Error(`shared/ui/palette.css does not define ${variable}`);
  if (/^#[0-9a-f]{6}$/i.test(value))
    return `Color(hex: "${value.toLowerCase()}")`;
  const rgba = value.match(
    /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/,
  );
  if (!rgba)
    throw new Error(`${variable} is ${value}, neither #rrggbb nor rgba()`);
  const [, red, green, blue, alpha] = rgba;
  return `Color(hex: "#${hex(red)}${hex(green)}${hex(blue)}").opacity(${Number(alpha)})`;
}

await write(
  themeSwiftPath,
  `// ${banner("shared/ui/palette.css")}

import SwiftUI

extension Colours {
    /// Sikemux's own colours, which the island wears until the core sends the person's palette.
    static let own = Colours(
${Object.entries(COLOURS)
  .map(([name, variable]) => `        ${name}: ${swiftColour(variable)}`)
  .join(",\n")}
    )
}
`,
);
// Some shapes repeat an attribute on one tag. A page keeps the first; the notch's SVG reader rejects the whole drawing, so the repeats go.
const firstAttributes = (markup) =>
  markup.replace(/<[a-zA-Z][^>]*>/g, (tag) => {
    const seen = new Set();
    return tag.replace(/\s([a-zA-Z:-]+)="[^"]*"/g, (attribute, name) =>
      seen.has(name) ? "" : (seen.add(name), attribute),
    );
  });

const swiftString = (value) => JSON.stringify(value);

const server = await typescriptLoader();
let packEntries;
let compressedBytes = 0;
try {
  const { BUDDY_PACKS } = await server.ssrLoadModule(
    "/shared/buddies/catalogue.ts",
  );
  packEntries = BUDDY_PACKS.map((pack) => {
    const segments = [];
    for (const shape of pack.shapes) {
      for (const color of pack.colors) {
        for (const state of BUDDY_STATES) {
          const markup = firstAttributes(shape.draw(color, state, "notch"));
          if (markup.includes("\0"))
            throw new Error(`buddy ${pack.id}/${shape.id} contains a NUL byte`);
          segments.push(markup);
        }
      }
    }
    const packed = deflateRawSync(Buffer.from(segments.join("\0"), "utf8"), {
      level: 9,
    });
    compressedBytes += packed.length;
    return `    BuddyPackData(
        id: ${swiftString(pack.id)},
        shapes: [${pack.shapes.map((shape) => swiftString(shape.id)).join(", ")}],
        colors: ${pack.colors.length},
        compressed: ${swiftString(packed.toString("base64"))}
    )`;
  });
} finally {
  await server.close();
}

await write(
  buddiesSwiftPath,
  `// ${banner("shared/buddies")}

struct BuddyPackData: Sendable {
    let id: String
    let shapes: [String]
    let colors: Int
    /// Raw-deflated NUL-separated inner SVG markup ordered by shape, colour, then state (idle, working, waiting, done, error).
    let compressed: String
}

let buddyPacks: [BuddyPackData] = [
${packEntries.join(",\n")}
]
`,
);

console.log(
  `✓ ${entries.length} notch settings, ${Object.keys(COLOURS).length} colours and ${Math.round(compressedBytes / 1024)} KB of buddies`,
);
