// Rebuilds src/themes/ghostty.generated.ts from Ghostty's bundled theme files.
// Usage: node scripts/import-ghostty-themes.mjs [themes-dir]
// The themes come from iTerm2-Color-Schemes (MIT), which Ghostty ships as-is.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outputPath = resolve(root, "src/themes/ghostty.generated.ts");
const themesDir =
  process.argv[2] ??
  "/Applications/Ghostty.app/Contents/Resources/ghostty/themes";

const KEYS = [
  "background",
  "foreground",
  "cursor-color",
  "cursor-text",
  "selection-background",
];

function hex(value) {
  const match = value.trim().match(/^#?([0-9a-f]{6}|[0-9a-f]{3})$/i);
  if (!match) return null;
  const digits = match[1].toLowerCase();
  return digits.length === 3
    ? digits
        .split("")
        .map((d) => d + d)
        .join("")
    : digits;
}

function parse(text) {
  const fields = {};
  const palette = [];
  for (const line of text.split("\n")) {
    const [key, ...rest] = line.split("=");
    const value = rest.join("=").trim();
    if (key.trim() === "palette") {
      const [index, color] = value.split("=");
      palette[Number(index)] = hex(color);
    } else if (KEYS.includes(key.trim())) fields[key.trim()] = hex(value);
  }
  if (!fields.background || !fields.foreground) return null;
  if (palette.slice(0, 16).filter(Boolean).length !== 16) return null;
  return [
    fields.background,
    fields.foreground,
    fields["cursor-color"] ?? fields.foreground,
    fields["cursor-text"] ?? fields.background,
    fields["selection-background"] ?? "",
    ...palette.slice(0, 16),
  ].join(",");
}

const names = (await readdir(themesDir))
  .filter((name) => !name.startsWith("."))
  .sort((a, b) => a.localeCompare(b));
const rows = [];
for (const name of names) {
  const encoded = parse(await readFile(join(themesDir, name), "utf8"));
  if (encoded)
    rows.push(
      `    [\n        ${JSON.stringify(name)},\n        "${encoded}",\n    ],`,
    );
}
if (rows.length === 0)
  throw new Error(`no Ghostty themes found in ${themesDir}`);

await writeFile(
  outputPath,
  `// Generated by scripts/import-ghostty-themes.mjs. Do not edit.
// Each row: name, then background, foreground, cursor, cursor text, selection, and the 16 ANSI colours.
export const GHOSTTY_THEMES: readonly (readonly [string, string])[] = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${rows.length} themes to ${outputPath}`);
