#!/usr/bin/env node
// Writes the agent catalog in src/agents/catalog.json out for every place that
// names an agent or asks what it can do: the app's TypeScript and stylesheet,
// the core's Rust and the notch's Swift. `--check` fails when one is out of date
// instead of writing it.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { format, resolveConfig } from "prettier";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(root, "src/agents/catalog.json");
const tsPath = resolve(root, "src/agents/generated/catalog.ts");
const cssPath = resolve(root, "src/styles/generated/agent-brands.css");
const rustPath = resolve(
  root,
  "src-tauri/crates/sikemux-core/src/agent_catalog.rs",
);
const swiftPath = resolve(
  root,
  "src-tauri/notch/Sources/NotchKit/AgentCatalog.generated.swift",
);
const check = process.argv.includes("--check");
const banner =
  "Generated by scripts/generate-agent-catalog.mjs from src/agents/catalog.json. Do not edit by hand.";

const FLAGS = [
  "featured",
  "accounts",
  "usage",
  "deletableChats",
  "resumesByPath",
  "relocatableSessions",
];
const DRIVERS = ["claude", "codex", "muse", "acp"];
const PROVIDERS = ["routed", "reads"];

/** Everything the app paints in an agent's colour, as a selector with `%` for the agent and the property it sets. */
const BRANDED = [
  [".agent-glyph.%", "color"],
  [".agent-usage.%", "--usage-fill"],
  [".desk.%", "--desk-agent"],
  [".proj-pip-%", "color"],
];

const { agents } = JSON.parse(await readFile(sourcePath, "utf8"));
if (!Array.isArray(agents) || agents.length === 0)
  throw new Error("src/agents/catalog.json lists no agents");
for (const agent of agents) {
  if (!/^[a-z]+$/.test(agent.type))
    throw new Error(
      `agent type ${JSON.stringify(agent.type)} is not lowercase letters`,
    );
  if (!/^#[0-9a-f]{6}$/.test(agent.brand))
    throw new Error(
      `${agent.type} brand ${agent.brand} is not a #rrggbb colour`,
    );
  for (const field of ["label", "about", "command"]) {
    if (typeof agent[field] !== "string" || !agent[field])
      throw new Error(`${agent.type} has no ${field}`);
  }
  for (const flag of FLAGS) {
    if (typeof agent[flag] !== "boolean")
      throw new Error(`${agent.type} does not say whether it has ${flag}`);
  }
  if (
    !Array.isArray(agent.efforts) ||
    !agent.efforts.every((effort) => /^[a-z]+$/.test(effort))
  )
    throw new Error(
      `${agent.type} efforts must list the reasoning efforts its CLI takes`,
    );
  if (
    agent.install !== null &&
    !/^curl -fsSL https:\/\/\S+ \| (ba)?sh$/.test(agent.install ?? "")
  )
    throw new Error(
      `${agent.type} install must be null or "curl -fsSL https://… | sh"`,
    );
  if (
    agent.login !== null &&
    !(
      Array.isArray(agent.login) &&
      agent.login.length > 0 &&
      agent.login.every((arg) => /^[a-z-]+$/.test(arg))
    )
  )
    throw new Error(
      `${agent.type} login must be null or its sign-in arguments`,
    );
}
const isArgs = (value) =>
  Array.isArray(value) &&
  value.every((arg) => typeof arg === "string" && arg.length > 0);
const isName = (value) => typeof value === "string" && value.length > 0;
for (const agent of agents) {
  const fail = (message) => {
    throw new Error(`${agent.type} ${message}`);
  };
  if (!isArgs(agent.probe) || agent.probe.length === 0)
    fail("probe must list the arguments that check its CLI runs");
  if (
    !isArgs(agent.installPaths) ||
    !agent.installPaths.every((path) => /^[~/]/.test(path))
  )
    fail("installPaths must list paths starting with ~ or /");
  if (!isArgs(agent.gitShimArgs))
    fail("gitShimArgs must list what makes its commands find Sikemux's git");
  const { home, terminal, chat } = agent;
  if (
    home !== null &&
    !(
      isName(home?.variable) &&
      isName(home?.dir) &&
      (home.within === undefined || isName(home.within)) &&
      (home.sessions === undefined || isName(home.sessions))
    )
  )
    fail(
      "home must be null or { variable, dir, within?, sessions?, private? }",
    );
  if (agent.accounts && !home?.sessions)
    fail("keeps accounts, so its home must name its sessions folder");
  if (
    !isArgs(terminal?.normal) ||
    !(terminal.bypass === null || isArgs(terminal.bypass)) ||
    !(
      terminal.effort === null ||
      (isArgs(terminal.effort) &&
        terminal.effort.length === 2 &&
        terminal.effort[1].includes("{}"))
    ) ||
    !(isName(terminal.resume?.flag) !== isName(terminal.resume?.subcommand)) ||
    !isArgs(terminal.withChoices)
  )
    fail(
      'terminal must be { normal, bypass, effort: [flag, "…{}…"] | null, resume: { flag } | { subcommand }, withChoices }',
    );
  if (
    chat !== null &&
    !(
      DRIVERS.includes(chat?.driver) &&
      (chat.driver === "acp"
        ? isArgs(chat.args) &&
          (chat.modes === undefined ||
            (isName(chat.modes.normal) && isName(chat.modes.bypass)))
        : chat.args === undefined && chat.modes === undefined)
    )
  )
    fail(
      `chat must be null or { driver: ${DRIVERS.join(" | ")} }, with args and optional modes for acp`,
    );
  const privateHome = home?.private;
  if (
    privateHome !== undefined &&
    !(
      isName(privateHome?.config) &&
      typeof privateHome.emptyConfig === "string" &&
      isName(privateHome.sessionStore) &&
      typeof privateHome.sessionStoreIsFolder === "boolean"
    )
  )
    fail(
      "home.private must be absent or { config, emptyConfig, sessionStore, sessionStoreIsFolder }",
    );
  if (agent.commitMessages !== null && !isName(agent.commitMessages?.model))
    fail(
      "commitMessages must be null or { model } it writes commit messages with",
    );
  if (agent.providers !== null && !PROVIDERS.includes(agent.providers))
    fail(`providers must be null or ${PROVIDERS.join(" | ")}`);
}
if (new Set(agents.map((agent) => agent.type)).size !== agents.length)
  throw new Error("src/agents/catalog.json lists an agent twice");

async function emit(path, contents) {
  let actual = null;
  try {
    actual = await readFile(path, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (actual === contents) return;
  if (check) throw new Error(`Generated agent catalog is stale: ${path}`);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
}

async function pretty(path, source) {
  return format(source, { ...(await resolveConfig(path)), filepath: path });
}

const entries = agents.map((agent) => ({
  type: agent.type,
  label: agent.label,
  about: agent.about,
  command: agent.command,
  brand: agent.brand,
  ...Object.fromEntries(FLAGS.map((flag) => [flag, agent[flag]])),
  bypass: agent.terminal.bypass !== null,
  commitMessages: agent.commitMessages !== null,
  efforts: agent.efforts,
  install: agent.install,
  login: agent.login,
  chat: agent.chat?.driver ?? null,
}));

await emit(
  tsPath,
  await pretty(
    tsPath,
    `// ${banner}
export const AGENT_CATALOG = ${JSON.stringify(entries)} as const;
`,
  ),
);

await emit(
  cssPath,
  await pretty(
    cssPath,
    `/* ${banner} */
:root {
${agents.map((agent) => `--brand-${agent.type}: ${agent.brand};`).join("\n")}
}
${BRANDED.flatMap(([selector, property]) =>
  agents.map(
    (agent) =>
      `${selector.replace("%", agent.type)} { ${property}: var(--brand-${agent.type}); }`,
  ),
).join("\n")}
`,
  ),
);

const pascal = (type) => type[0].toUpperCase() + type.slice(1);
const snake = (name) =>
  name.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
const rustString = (value) => JSON.stringify(value);

const RUST_WIDTH = 100;
const RUST_ARRAY_WIDTH = 60;
const rustOption = (value, write) =>
  value === null || value === undefined ? "None" : `Some(${write(value)})`;

/** `name: &[…],` at `indent` spaces, wrapped the way rustfmt wraps a list of short strings. */
function rustList(indent, name, items) {
  const pad = " ".repeat(indent);
  const quoted = items.map(rustString);
  const line = `${pad}${name}: &[${quoted.join(", ")}],`;
  if (line.length <= RUST_WIDTH && quoted.join(", ").length <= RUST_ARRAY_WIDTH)
    return line;
  const inner = " ".repeat(indent + 4);
  const rows = [];
  for (const item of quoted) {
    const last = rows.at(-1);
    if (last && `${last} ${item},`.length <= RUST_WIDTH)
      rows[rows.length - 1] = `${last} ${item},`;
    else rows.push(`${inner}${item},`);
  }
  return `${pad}${name}: &[\n${rows.join("\n")}\n${pad}],`;
}

function rustEntry(agent) {
  const { home, terminal, chat } = agent;
  const privateHome = home?.private;
  const resume = terminal.resume.flag
    ? `Resume::Flag(${rustString(terminal.resume.flag)})`
    : `Resume::Subcommand(${rustString(terminal.resume.subcommand)})`;
  const modes = chat?.modes
    ? `            modes: Some(AcpModes {
                normal: ${rustString(chat.modes.normal)},
                bypass: ${rustString(chat.modes.bypass)},
            }),`
    : "            modes: None,";
  const driver = !chat
    ? "        chat: None,"
    : chat.driver === "acp"
      ? `        chat: Some(ChatDriver::Acp {
${rustList(12, "args", chat.args)}
${modes}
        }),`
      : `        chat: Some(ChatDriver::${pascal(chat.driver)}),`;
  const privateField = privateHome
    ? `            private: Some(PrivateHome {
                config: ${rustString(privateHome.config)},
                empty_config: ${rustString(privateHome.emptyConfig)},
                session_store: ${rustString(privateHome.sessionStore)},
                session_store_is_folder: ${privateHome.sessionStoreIsFolder},
            }),`
    : "            private: None,";
  const homeField = home
    ? `        home: Some(Home {
            variable: ${rustString(home.variable)},
            dir: ${rustString(home.dir)},
            within: ${rustOption(home.within, rustString)},
            sessions: ${rustOption(home.sessions, rustString)},
${privateField}
        }),`
    : "        home: None,";
  const bypass = terminal.bypass
    ? `            bypass: Some(&[${terminal.bypass.map(rustString).join(", ")}]),`
    : "            bypass: None,";
  const effort = terminal.effort
    ? `            effort: Some([${terminal.effort.map(rustString).join(", ")}]),`
    : "            effort: None,";
  return `    AgentEntry {
        kind: ${rustString(agent.type)},
        label: ${rustString(agent.label)},
        command: ${rustString(agent.command)},
        brand: ${rustString(agent.brand)},
${FLAGS.map((flag) => `        ${snake(flag)}: ${agent[flag]},`).join("\n")}
        bypass: ${terminal.bypass !== null},
        commit_model: ${rustOption(agent.commitMessages?.model, rustString)},
${rustList(8, "efforts", agent.efforts)}
${rustList(8, "probe", agent.probe)}
${rustList(8, "install_paths", agent.installPaths)}
${rustList(8, "git_shim_args", agent.gitShimArgs)}
${homeField}
        terminal: Terminal {
${rustList(12, "normal", terminal.normal)}
${bypass}
${effort}
            resume: ${resume},
${rustList(12, "with_choices", terminal.withChoices)}
        },
${driver}
        providers: ${rustOption(agent.providers, (providers) => `ProviderUse::${pascal(providers)}`)},
    },`;
}

await emit(
  rustPath,
  `// ${banner}
use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum AgentKind {
${agents.map((agent) => `    ${pascal(agent.type)},`).join("\n")}
}

/// How the CLI is told which session to resume.
#[derive(Debug)]
pub enum Resume {
    /// \`<flag> <session>\` after its other arguments.
    Flag(&'static str),
    /// \`<subcommand>\` before its other arguments and the session after them.
    Subcommand(&'static str),
}

/// The CLI's flags in a terminal.
pub struct Terminal {
    /// Sikemux's Normal mode.
    pub normal: &'static [&'static str],
    /// YOLO, when the CLI has one.
    pub bypass: Option<&'static [&'static str]>,
    /// The flag taking a reasoning effort, and its value with \`{}\` for the effort.
    pub effort: Option<[&'static str; 2]>,
    pub resume: Resume,
    /// What the CLI needs once a model or effort is chosen.
    pub with_choices: &'static [&'static str],
}

/// The session modes an ACP agent's permission modes are.
pub struct AcpModes {
    pub normal: &'static str,
    pub bypass: &'static str,
}

/// How the core drives the agent in a chat.
pub enum ChatDriver {
    Claude,
    Codex,
    Muse,
    /// The agent's own ACP mode, started with \`args\`.
    Acp {
        args: &'static [&'static str],
        modes: Option<AcpModes>,
    },
}

/// The folder the CLI keeps its settings and sessions in: \`variable\`, else
/// \`dir\` under the home folder, then \`within\` either.
pub struct Home {
    pub variable: &'static str,
    pub dir: &'static str,
    pub within: Option<&'static str>,
    /// The folder its saved sessions sit in.
    pub sessions: Option<&'static str>,
    /// A private copy Sikemux gives each of the agent's launches.
    pub private: Option<PrivateHome>,
}

/// A private copy of the agent's home Sikemux can change without touching the person's.
pub struct PrivateHome {
    pub config: &'static str,
    /// What the config holds when the person has none.
    pub empty_config: &'static str,
    /// The agent's saved sessions, shared with the person's own home.
    pub session_store: &'static str,
    pub session_store_is_folder: bool,
}

/// How the agent reaches a connected model provider.
pub enum ProviderUse {
    /// Sikemux points it at one in place of its maker's account.
    Routed,
    /// It reads every connected provider's key from its environment.
    Reads,
}

pub struct AgentEntry {
    pub kind: &'static str,
    pub label: &'static str,
    pub command: &'static str,
    pub brand: &'static str,
${FLAGS.map((flag) => `    pub ${snake(flag)}: bool,`).join("\n")}
    pub bypass: bool,
    /// The model it writes commit messages with, when it can.
    pub commit_model: Option<&'static str>,
    /// The reasoning efforts the CLI's own flag takes.
    pub efforts: &'static [&'static str],
    /// Arguments that answer whether the CLI runs, without side effects.
    pub probe: &'static [&'static str],
    /// Where its installers put the CLI off PATH.
    pub install_paths: &'static [&'static str],
    /// What makes the commands it runs find Sikemux's git ahead of the system's.
    pub git_shim_args: &'static [&'static str],
    pub home: Option<Home>,
    pub terminal: Terminal,
    pub chat: Option<ChatDriver>,
    pub providers: Option<ProviderUse>,
}

pub const AGENTS: &[AgentEntry] = &[
${agents.map(rustEntry).join("\n")}
];

impl AgentKind {
    pub const ALL: [AgentKind; ${agents.length}] = [
${agents.map((agent) => `        AgentKind::${pascal(agent.type)},`).join("\n")}
    ];

    pub fn entry(self) -> &'static AgentEntry {
        &AGENTS[self as usize]
    }

    pub fn as_str(self) -> &'static str {
        self.entry().kind
    }

    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|kind| kind.as_str() == name)
    }
}

pub fn agent(name: &str) -> Option<&'static AgentEntry> {
    AGENTS.iter().find(|entry| entry.kind == name)
}
`,
);

const swiftString = (value) => JSON.stringify(value);

await emit(
  swiftPath,
  `// ${banner}

let agentNames: [String: String] = [
${agents.map((agent) => `    ${swiftString(agent.type)}: ${swiftString(agent.label)},`).join("\n")}
]
`,
);

console.log(`✓ ${agents.length} agents in the catalog`);
