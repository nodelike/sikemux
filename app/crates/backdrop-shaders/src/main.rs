//! Writes the phones' backdrop shaders from the kinds the Mac draws, `app/assets/shaders/kinds`:
//! Metal functions the iPhone's SwiftUI shaders call, and GLSL ones Android's fragment shaders
//! call. `--check` fails when either file on disk differs from what it would write.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use naga::back::{glsl, msl};

const KINDS: &str = "app/assets/shaders/kinds";
const IPHONE: &str = "mobile/ios/Sikemux/UI/BackdropKinds.generated.h";
const ANDROID: &str = "mobile/app/src/ui/backdropKinds.generated.ts";
/// naga writes only a module with an entry point, so the kinds get an empty one, cut from what it writes.
const ENTRY: &str = "backdrop_kinds";
const HEADER: &str = "Generated by app/crates/backdrop-shaders from app/assets/shaders/kinds; run `pnpm backdrop-shaders`.";

fn main() -> ExitCode {
    let check = std::env::args().any(|argument| argument == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let (module, info) = parse(&root.join(KINDS));
    let outputs = [
        (IPHONE, format!("// {HEADER}\n\n{}", metal(&module, &info))),
        (
            ANDROID,
            format!(
                "// {HEADER}\n\n/** The kinds' functions, to put after a fragment shader's `#version 300 es`. */\nexport const backdropKinds = {};\n",
                quoted(&glsl(&module, &info))
            ),
        ),
    ];
    let mut stale = false;
    for (path, text) in outputs {
        let file = root.join(path);
        if check {
            if std::fs::read_to_string(&file).ok().as_deref() != Some(text.as_str()) {
                eprintln!("{path} is out of date; run `pnpm backdrop-shaders`");
                stale = true;
            }
        } else {
            std::fs::write(&file, text).unwrap_or_else(|error| panic!("write {path}: {error}"));
        }
    }
    if stale {
        ExitCode::FAILURE
    } else {
        ExitCode::SUCCESS
    }
}

fn parse(folder: &Path) -> (naga::Module, naga::valid::ModuleInfo) {
    let mut files: Vec<PathBuf> = std::fs::read_dir(folder)
        .unwrap_or_else(|error| panic!("{}: {error}", folder.display()))
        .map(|entry| entry.expect("a kind's file").path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "wgsl")
        })
        .collect();
    files.sort();
    let mut source: String = files
        .iter()
        .map(|path| std::fs::read_to_string(path).expect("read a kind") + "\n")
        .collect();
    source += &format!("@fragment\nfn {ENTRY}() {{}}\n");
    let module = naga::front::wgsl::parse_str(&source)
        .unwrap_or_else(|error| panic!("{}", error.emit_to_string_with_path(&source, KINDS)));
    let info = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::empty(),
    )
    .validate(&module)
    .unwrap_or_else(|error| panic!("{}", error.emit_to_string_with_path(&source, KINDS)));
    (module, info)
}

fn metal(module: &naga::Module, info: &naga::valid::ModuleInfo) -> String {
    let options = msl::Options {
        lang_version: (2, 0),
        ..Default::default()
    };
    let (text, _) = msl::write_string(module, info, &options, &msl::PipelineOptions::default())
        .unwrap_or_else(|error| panic!("Metal: {error}"));
    let body = text
        .split_once('\n')
        .filter(|(first, _)| first.starts_with("// language:"))
        .map_or(text.as_str(), |(_, rest)| rest);
    before_entry(body, "fragment void ")
}

fn glsl(module: &naga::Module, info: &naga::valid::ModuleInfo) -> String {
    let options = glsl::Options {
        version: glsl::Version::Embedded {
            version: 300,
            is_webgl: false,
        },
        ..Default::default()
    };
    let pipeline = glsl::PipelineOptions {
        shader_stage: naga::ShaderStage::Fragment,
        entry_point: ENTRY.to_owned(),
        multiview: None,
    };
    let mut text = String::new();
    glsl::Writer::new(
        &mut text,
        module,
        info,
        &options,
        &pipeline,
        naga::proc::BoundsCheckPolicies::default(),
    )
    .and_then(|mut writer| writer.write())
    .unwrap_or_else(|error| panic!("GLSL: {error}"));
    let body = text
        .strip_prefix("#version 300 es\n")
        .expect("GLSL starts with its version");
    before_entry(body.trim_start(), "void main()")
}

/// What naga wrote before the empty entry point, which it writes last.
fn before_entry(text: &str, entry: &str) -> String {
    let at = text
        .find(&format!("\n{entry}"))
        .unwrap_or_else(|| panic!("no `{entry}` in what naga wrote"));
    format!("{}\n", text[..at].trim_end())
}

fn quoted(text: &str) -> String {
    let mut out = String::from("`");
    for character in text.chars() {
        match character {
            '`' | '\\' | '$' => {
                out.push('\\');
                out.push(character);
            }
            _ => out.push(character),
        }
    }
    out.push('`');
    out
}
